const LANG_KEY = 'precision-lab-lang';
let lang = detect();
const listeners = new Set();

function detect() {
  try {
    const s = localStorage.getItem(LANG_KEY);
    if (s === 'cs' || s === 'en') return s;
  } catch { /* storage unavailable */ }
  return (navigator.language || '').toLowerCase().startsWith('cs') ? 'cs' : 'en';
}

export function getLang() {
  return lang;
}

export function setLang(l) {
  lang = l === 'cs' ? 'cs' : 'en';
  try { localStorage.setItem(LANG_KEY, lang); } catch { /* ignore */ }
  document.documentElement.lang = lang;
  listeners.forEach((fn) => fn(lang));
}

export function onLangChange(fn) {
  listeners.add(fn);
}

/** Translate a key. Params may themselves be {key} objects, which are translated too. */
export function t(key, params = {}) {
  const dict = DICT[lang];
  const tpl = dict[key] ?? DICT.en[key] ?? key;
  const p = {};
  for (const [k, v] of Object.entries(params)) {
    p[k] = v && typeof v === 'object' && 'key' in v ? t(v.key, v.params) : v;
  }
  return fill(tpl, p);
}

/** Escape-free variant for templates whose params are already HTML. */
export function th(key, params = {}) {
  return t(key, params);
}

export function errorText(err) {
  return engineErrorText(err, lang);
}

/** Fill elements with data-i18n / data-i18n-html / data-i18n-title / data-i18n-aria attributes. */
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
}

